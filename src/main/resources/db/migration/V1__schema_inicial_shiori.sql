    titulo varchar(200),
    capa_url varchar(500),
    url_leitura varchar(500),
    status_leitura varchar(255) not null check ((status_leitura in ('LENDO','ENGAVETADO','TERMINOU','PLANEJADO','PAUSADO','DROPOU','ABDICOU'))),
    tipo_obra varchar(255) check ((tipo_obra in ('MANGA','MANHWA','MANHUA','LIGHT_NOVEL','WEB_NOVEL','COMIC','LIVRO','NOVEL'))),
    visibilidade varchar(255) not null check ((visibilidade in ('PRIVADO','RESTRITO','PUBLICO'))),
    primary key (id)
);

create table if not exists tb_no_federado (
    ativo boolean not null,
    total_obras_enviadas integer not null,
    total_obras_recebidas integer not null,
    id bigint generated by default as identity,
