    mangadex_id varchar(100),
    titulo_original varchar(150),
    titulo_principal varchar(150) not null,
    capa_url varchar(500),
    sinopse TEXT,
    status_catalogo varchar(255) not null check ((status_catalogo in ('PRIVADO','COMUNITARIO','OFICIAL'))),
    status_publicacao varchar(255) not null check ((status_publicacao in ('EM_LANCAMENTO','CONCLUIDO','EM_HIATO','CANCELADO','NAO_LANCADO'))),
    tipo_obra varchar(255) not null check ((tipo_obra in ('MANGA','MANHWA','MANHUA','LIGHT_NOVEL','WEB_NOVEL','COMIC','LIVRO','NOVEL'))),
    primary key (id)
);

create table if not exists tb_obra_avisos_conteudo (
