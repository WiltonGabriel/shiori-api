create table if not exists tb_atividade_feed (
    capitulo_snapshot float(53),
    nota_snapshot float(53),
    data_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    item_catalogo_id bigint,
    obra_id bigint,
    usuario_id bigint not null,
    usuario_apelido_snapshot varchar(100),
    obra_titulo_snapshot varchar(200),
    descricao varchar(500) not null,
    obra_capa_url_snapshot varchar(500),
    usuario_foto_url_snapshot varchar(500),
    tipo_atividade varchar(255) not null check ((tipo_atividade in ('INICIOU_LEITURA','ATUALIZOU_PROGRESSO','CONCLUIU_LEITURA','ENGAVETOU_LEITURA','AVALIOU_OBRA','ADICIONOU_ESTANTE'))),
    primary key (id)
);

create table if not exists tb_broadcast_sistema (
    ativo boolean not null,
    admin_criador_id bigint,
    data_criacao timestamp(6) not null,
    data_expiracao timestamp(6),
    id bigint generated by default as identity,
    nivel varchar(30) not null check ((nivel in ('INFO','AVISO','URGENTE'))),
    titulo varchar(150) not null,
    mensagem TEXT not null,
    primary key (id)
);

create table if not exists tb_comentario (
    ativo boolean not null,
    contem_spoiler boolean not null,
    data_atualizacao timestamp(6),
    data_criacao timestamp(6) not null,
    historico_leitura_id bigint,
    id bigint generated by default as identity,
    obra_id bigint,
    usuario_id bigint,
    texto TEXT not null,
    primary key (id)
);

create table if not exists tb_conexao_usuario (
    data_atualizacao timestamp(6),
    data_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    recebedor_id bigint not null,
    solicitante_id bigint not null,
    status varchar(255) not null check ((status in ('PENDENTE','ACEITA','BLOQUEADA'))),
    primary key (id),
    constraint uk_conexao_solicitante_recebedor unique (solicitante_id, recebedor_id)
);

create table if not exists tb_consentimento_usuario (
    ativo boolean not null,
    cookies_analiticos boolean not null,
    cookies_funcionais boolean not null,
    cookies_marketing boolean not null,
    cookies_necessarios boolean not null,
    data_consentimento timestamp(6) not null,
    id bigint generated by default as identity,
    usuario_id bigint not null,
    versao_politica_privacidade varchar(30) not null,
    versao_termos_uso varchar(30) not null,
    ip_origem varchar(255),
    user_agent varchar(255),
    primary key (id)
);

create table if not exists tb_denuncia_comentario (
    comentario_id bigint not null,
    data_criacao timestamp(6) not null,
    data_resolucao timestamp(6),
    id bigint generated by default as identity,
    usuario_id bigint not null,
    detalhes TEXT,
    motivo varchar(255) not null check ((motivo in ('SPAM','DADOS_FALSOS_OU_DUPLICADOS','CONTEUDO_IMPROPRIO','SPOILER_NO_TITULO_OU_CAPA','OUTRO'))),
    parecer_moderacao TEXT,
    status varchar(255) not null check ((status in ('PENDENTE','PROCEDENTE','IMPROCEDENTE'))),
    primary key (id),
    constraint uk_denuncia_usuario_comentario unique (usuario_id, comentario_id)
);

create table if not exists tb_denuncia_obra (
    data_criacao timestamp(6) not null,
    data_resolucao timestamp(6),
    id bigint generated by default as identity,
    obra_id bigint not null,
    usuario_id bigint not null,
    detalhes TEXT,
    motivo varchar(255) not null check ((motivo in ('SPAM','DADOS_FALSOS_OU_DUPLICADOS','CONTEUDO_IMPROPRIO','SPOILER_NO_TITULO_OU_CAPA','OUTRO'))),
    parecer_moderacao TEXT,
    status varchar(255) not null check ((status in ('PENDENTE','PROCEDENTE','IMPROCEDENTE'))),
    primary key (id)
);

create table if not exists tb_feature_flag (
    ativado boolean not null,
    data_atualizacao timestamp(6) not null,
    id bigint generated by default as identity,
    chave varchar(60) not null unique,
    nome varchar(120) not null,
    descricao varchar(255),
    primary key (id)
);

create table if not exists tb_genero (
    id bigint generated by default as identity,
    nome varchar(60) not null unique,
    slug varchar(60) not null unique,
    descricao varchar(255),
    primary key (id)
);

create table if not exists tb_historico_leitura (
    avaliacao_ciclo float(53),
    capitulo_final float(53) not null,
    capitulo_inicial float(53) not null,
    data_leitura date not null,
    id bigint generated by default as identity,
    item_catalogo_id bigint not null,
    ultima_atualizacao timestamp(6) not null,
    anotacoes TEXT,
    primary key (id)
);

create table if not exists tb_item_catalogo (
    avaliacao_pessoal float(53),
    progresso_atual float(53) not null,
    sincronizar_metadados boolean not null,
    total_capitulos integer,
    total_volumes integer,
    volume_atual float(53) not null,
    data_adicao timestamp(6) not null,
    id bigint generated by default as identity,
    obra_id bigint,
    ultima_atualizacao timestamp(6) not null,
