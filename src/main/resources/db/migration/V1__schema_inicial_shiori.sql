    ativo boolean not null,
    onboarding_concluido boolean not null,
    pontos_confianca integer not null,
    strikes integer not null,
    data_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    ultima_atualizacao timestamp(6) not null,
    role varchar(30) not null check ((role in ('ROLE_USER','ROLE_ADMIN','ROLE_CURADOR'))),
    apelido varchar(50) unique,
    fuso_horario varchar(50) not null,
