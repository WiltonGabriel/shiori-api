CREATE TABLE IF NOT EXISTS tb_sugestao_tag_obra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id BIGINT NOT NULL,
    tag_id BIGINT,
    nome_tag VARCHAR(60) NOT NULL,
    usuario_sugeridor_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('PENDENTE', 'APROVADA', 'REJEITADA')),
    justificativa VARCHAR(255),
    data_sugestao TIMESTAMP(6) NOT NULL,
    admin_avaliador_id BIGINT,
    data_avaliacao TIMESTAMP(6),
    motivo_rejeicao VARCHAR(255),
    CONSTRAINT fk_sugestao_tag_obra FOREIGN KEY (obra_id) REFERENCES tb_obra (id) ON DELETE CASCADE,
    CONSTRAINT fk_sugestao_tag_tag FOREIGN KEY (tag_id) REFERENCES tb_tag (id) ON DELETE SET NULL,
    CONSTRAINT fk_sugestao_tag_usuario FOREIGN KEY (usuario_sugeridor_id) REFERENCES tb_usuario (id),
    CONSTRAINT fk_sugestao_tag_admin FOREIGN KEY (admin_avaliador_id) REFERENCES tb_usuario (id)
);

CREATE INDEX IF NOT EXISTS idx_sugestao_tag_obra_status ON tb_sugestao_tag_obra (obra_id, status);
CREATE INDEX IF NOT EXISTS idx_sugestao_tag_usuario ON tb_sugestao_tag_obra (usuario_sugeridor_id);
CREATE INDEX IF NOT EXISTS idx_sugestao_tag_status ON tb_sugestao_tag_obra (status);
